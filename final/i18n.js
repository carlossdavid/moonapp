export function translate(text, language = 'es') {
  if (language !== 'en' || typeof text !== 'string') return text;
  const trimmed = text.trim();
  let output = words.get(trimmed);
  if (!output) {
    for (const [pattern, replacement] of phrases) {
      if (pattern.test(trimmed)) { output = trimmed.replace(pattern, replacement); break; }
    }
  }
  if (!output) return text;
  return text.replace(trimmed, output);
}

export function localizeDocument(doc, language) {
  if (language !== 'en') return;
  doc.documentElement.lang = 'en';
  const visit = node => {
    if (node.nodeType === 3) {
      if (node.parentElement?.closest('script,style')) return;
      const translated = translate(node.nodeValue, language);
      if (translated !== node.nodeValue) node.nodeValue = translated;
    } else if (node.nodeType === 1) {
      for (const attribute of ['title', 'aria-label', 'aria-valuetext', 'placeholder', 'alt']) {
        if (node.hasAttribute(attribute)) {
          const value = node.getAttribute(attribute);
          const translated = translate(value, language);
          if (translated !== value) node.setAttribute(attribute, translated);
        }
      }
      for (const child of node.childNodes) visit(child);
    }
  };
  visit(doc.body);
  new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') visit(record.target);
      else if (record.type === 'attributes') visit(record.target);
      else for (const node of record.addedNodes) visit(node);
    }
  }).observe(doc.body, { subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: ['title', 'aria-label', 'aria-valuetext', 'placeholder', 'alt'] });
}
