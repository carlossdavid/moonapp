import assert from 'node:assert/strict';
import { SolarProgress } from './solarProgress.js';
import { SEGUNDOS_REALES_POR_DIA } from '../../src/systems/EnergySystem.js';

const progress = new SolarProgress();
assert.equal(SEGUNDOS_REALES_POR_DIA, 300);
assert.equal(progress.cleanCount, 0);
assert.equal(progress.discovered, false);
progress.discovered = true;
progress.markClean('Panel solar 1');
progress.markClean('Panel solar 1');
assert.equal(progress.cleanCount, 1, 'repetir el mismo panel no abre la puerta');
progress.tick(60);
progress.markClean('Panel solar 2');
assert.equal(progress.cleanCount, 2);
progress.tick(240);
assert.equal(progress.isClean('Panel solar 1'), false, 'caduca tras un día de juego');
assert.equal(progress.isClean('Panel solar 2'), true, 'cada panel conserva su propio tiempo');
assert.equal(progress.cleanCount, 1);
progress.markClean('Panel solar 1');
assert.equal(progress.cleanCount, 2, 'un panel que volvió a ensuciarse puede limpiarse');
progress.tick(60);
assert.equal(progress.cleanCount, 1);
progress.tick(240);
assert.equal(progress.cleanCount, 0);
assert.equal(progress.discovered, true, 'la explicación sigue marcada aunque caducan los paneles');
assert.throws(() => progress.tick(-1));
assert.throws(() => progress.tick(NaN));
console.log('Dos paneles distintos, caducidad individual y explicación única: OK');
