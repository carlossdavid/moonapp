import assert from 'node:assert/strict';
import { BeamCleaning, COLS, ROWS, PANEL, PORTS } from './beamCleaning.js';

const model = new BeamCleaning();
assert.equal(COLS * ROWS, 24);
assert.equal(PORTS.length, 2);
assert.ok(PANEL.w > 0 && PANEL.h > 0);
assert.equal(model.phase, 'connect');
assert.equal(model.progress, 0);
assert.equal(model.activate(), false, 'no se activa sin las dos conexiones');
model.tick(100);
assert.equal(model.progress, 0, 'el polvo no se limpia por pasar el tiempo sin activar');
assert.equal(model.connect(0), true);
assert.equal(model.connect(0), false, 'no se conecta dos veces la misma toma');
assert.equal(model.activate(), false, 'solo A no basta para activar el haz');
assert.equal(model.connect(9), false, 'un conector inexistente no sirve');
assert.equal(model.connect(1), true);
assert.equal(model.phase, 'ready');
assert.equal(model.progress, 0, 'conectar cables no limpia el panel');
assert.equal(model.activate(), true);
assert.equal(model.activate(), false, 'no hay una segunda activación');
model.tick(1);
assert.ok(model.cleanCells > 0 && model.cleanCells < 24);
assert.equal(model.complete, false, 'no se termina parcialmente');
assert.equal(model.connect(0), false, 'no se cambia el cableado durante el barrido');
model.tick(10);
assert.equal(model.cleanCells, 24);
assert.equal(model.progress, 100);
assert.equal(model.complete, true);
assert.ok(model.dust.every(cell => cell === false), 'no queda polvo de juego en ningún sector');
model.reset();
assert.equal(model.progress, 0);
assert.deepEqual(model.connected, [false, false]);
assert.equal(model.complete, false);
assert.equal(model.connect(1), true, 'los cables pueden conectarse en cualquier orden');
assert.equal(model.connect(0), true);
assert.equal(model.activate(), true);
model.tick(0.48);
model.reset();
assert.equal(model.cleanCells, 0, 'reiniciar durante el barrido borra el avance');
assert.equal(model.activate(), false, 'tras reiniciar hay que conectar de nuevo A y B');
assert.throws(() => model.tick(-1));
assert.throws(() => model.tick(NaN));
console.log('Cableado doble, activación y limpieza 24/24: OK');
